// Mechanical pass-through of OUR receiver ports only, never vendor RTL.
import fs from 'node:fs';import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const text=fs.readFileSync(new URL('../rtl/af_receive_pipeline.sv',import.meta.url),'utf8');
const m=text.match(/module af_receive_pipeline #\(([\s\S]*?)\)\(([\s\S]*?)\n\);/);
if(!m)throw Error('Receiver header not recognized');
const params=m[1].replace('SLOTS=10','SLOTS=5').replace('WORDS_PER_PACKET=10','WORDS_PER_PACKET=20').replace('DESC_DEPTH=64','DESC_DEPTH=256');
let direction='',width='';const ports=[];
for(const token of m[2].replace(/\/\/[^\n]*/g,'').split(',')){
 const s=token.trim(),d=s.match(/^(input|output)\s+wire\s*(\[[^\]]+\])?\s*(\w+)$/);
 let name;if(d){direction=d[1];width=d[2]??'';name=d[3];}else if(/^\w+$/.test(s)){name=s;}else throw Error('Bad receiver port '+s);
 ports.push({name,direction,width});
}
const removed=new Set(['rx_clk','s_data','s_keep','s_valid','s_last','s_error']);
const decl=ports.filter(p=>!removed.has(p.name)).map(p=>` ${p.direction} wire ${p.width} ${p.name}`);
decl.push(' input wire init_clk,gt_ref_clk_p,gt_ref_clk_n',' input wire [3:0] gt_rxp,gt_rxn',' input wire [11:0] gt_loopback',
 ' output wire [3:0] gt_txp,gt_txn',' output wire mac_rx_clk,mac_usr_rx_reset,mac_usr_tx_reset,mac_rx_aligned,mac_rx_status',' output wire [2:0] mac_bad_fcs');
const signals={rx_clk:'mac_rx_clk',s_data:'mac_data',s_keep:'mac_keep',s_valid:'mac_valid && !mac_usr_rx_reset',s_last:'mac_last',s_error:'mac_error'};
const source=`// Generated by scripts/generate-cmac-shell.mjs from our receiver interface.\n// Real CMAC/GT -> native AXIS -> packet-atomic CDC -> real ring and raw RAM.\nmodule af_cmac_receive_shell #(\n${params.trim()}\n)(\n${decl.join(',\n')}\n);\n`+
` wire [511:0] mac_data;wire [63:0] mac_keep;wire mac_valid,mac_last,mac_error;\n`+
` af_cmac_rx network(.init_clk(init_clk),.rst_n(rst_n),.gt_ref_clk_p(gt_ref_clk_p),.gt_ref_clk_n(gt_ref_clk_n),\n`+
`  .gt_rxp(gt_rxp),.gt_rxn(gt_rxn),.gt_loopback(gt_loopback),.gt_txp(gt_txp),.gt_txn(gt_txn),.rx_clk(mac_rx_clk),\n`+
`  .tx_data(512'd0),.tx_keep(64'd0),.tx_valid(1'b0),.tx_last(1'b0),.tx_error(1'b0),.tx_ready(),\n`+
`  .m_data(mac_data),.m_keep(mac_keep),.m_valid(mac_valid),.m_last(mac_last),.m_error(mac_error),\n`+
`  .usr_rx_reset(mac_usr_rx_reset),.usr_tx_reset(mac_usr_tx_reset),.rx_aligned(mac_rx_aligned),.rx_status(mac_rx_status),.rx_bad_fcs(mac_bad_fcs));\n`+
` af_receive_pipeline #(.SLOTS(SLOTS),.WORDS_PER_PACKET(WORDS_PER_PACKET),.DATA_DEPTH(DATA_DEPTH),.DESC_DEPTH(DESC_DEPTH)) receiver(\n`+
ports.map(p=>`  .${p.name}(${signals[p.name]??p.name})`).join(',\n')+'\n );\nendmodule\n';
fs.writeFileSync(new URL('../rtl/af_cmac_receive_shell.sv',import.meta.url),source);
console.log('Generated real CMAC shell with '+ports.length+' receiver ports at '+root.replaceAll('\\','/'));
