replace('always @(posedge rx_clk)if(running && sv)rx_beats=rx_beats+1;',
 'always @(posedge rx_clk)if(running && dut.mac_valid && !dut_rx_reset)rx_beats=rx_beats+1;');
replace('if(cycles>600000+BLOCKS*`AF_PIPE_PERIOD_TICKS)', 'if(cycles>2500000+BLOCKS*`AF_PIPE_PERIOD_TICKS)');
